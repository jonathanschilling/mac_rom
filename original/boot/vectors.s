| Macintosh 128K / 512K ROM Boot Code - Vectors, Hardware Init, Startup
|
| This file contains the ROM header, exception vectors, hardware
| initialization (VIA, IWM, SCC, RTC), and the startup sequence
| that leads to booting from disk.
|
| Hardware accessed during boot (see include/hwregs.inc):
| VIA (6522) at 0xEFE1FE - port B: RTC data/clock/enable, sound, mouse
| port A: sound volume and buffer, ROM overlay, disk SEL line, screen buffer
| SCC (8530) at 0x9FFFF8 (read) / 0xBFFFF9 (write) - serial ports, mouse
| IWM at 0xDFE1FF - floppy controller: phase lines CA0-CA2/LSTRB, drive enables, Q6/Q7
| Screen buffer at 0x3FA700 (21,888 bytes = 512x342/8)
|
| Boot sequence (from minivmac trace):
| 1. EBootStart - set initial SP, test SCC timing
| 2. Init VIA port B (RTC, sound) and read RTC date/PRAM
| 3. EraseScrnBuff - clear frame buffer to white
| 4. RAM test (memtest.s)
| 5. BootBeep - beep via VIA sound registers
| 6. InitSCC - reset serial communications controller
| 7. InitIOMgr - build Unit Table, install .Sony/.Sound drivers
| 8. BootFromDisk - attempt to load System from floppy/SCSI
|
| References:
| Inside Macintosh Vol II, Ch 13: Operating System Utilities (pp 367-392)
| Inside Macintosh Vol II, Ch 11: Vertical Retrace Manager (pp 347-354)
| Inside Macintosh Vol III, Ch 2: The Startup Sequence

