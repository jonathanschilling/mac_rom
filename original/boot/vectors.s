| GenExcps - exception vector dispatch table ($01AA-$01C3)
| Each entry is a 2-byte BSR.B to ToDeepShit. The BSR pushes a return
| address that encodes the exception number (offset / 2 from GenExcps).
| Vector 2=bus error (ID 0), vector 3=address error (ID 1), etc.
GenExcps:                                       | vector 2 (bus error, ID 0)
        BSR.B   ToDeepShit                      | bus error -- read/write to non-existent addr
EXCPT_ADDR_ERR:                                 | vector 3 (ID 1)
        BSR.B   ToDeepShit                      | address error -- word/long at odd addr
EXCPT_ILLEGAL_INST:                             | vector 4 (ID 2)
        BSR.B   ToDeepShit                      | illegal instruction
EXCPT_ZERO_DIVIDE:                              | vector 5 (ID 3)
        BSR.B   ToDeepShit                      | integer divide by zero
EXCPT_CHK:                                      | vector 6 (ID 4)
        BSR.B   ToDeepShit                      | CHK instruction out of bounds
EXCPT_TRAPV:                                    | vector 7 (ID 5)
        BSR.B   ToDeepShit                      | TRAPV overflow trap
EXCPT_PRIVILEGE:                                | vector 8 (ID 6)
        BSR.B   ToDeepShit                      | privilege violation (user mode ran priv opcode)
EXCPT_TRACE:                                    | vector 9 (ID 7)
        BSR.B   ToDeepShit                      | trace exception (T bit in SR set)
EXCPT_LINE_1010:                                | vector 10 (ID 8)
        BSR.B   ToDeepShit                      | line A (1010) emulator (unhandled A-trap)
EXCPT_LINE_1111:                                | vector 11 (ID 9)
        BSR.B   ToDeepShit                      | line F (1111) emulator
EXCPT_UNASSIGNED:                               | vectors 12-24 (ID 10)
        BSR.B   ToDeepShit                      | reserved / unassigned exception
IRQexception:                                   | auto-vectored IRQ entry
        ADDQ.W  #0x2,SP                         | strip format word from stacked IRQ frame
        BSR.B   ToDeepShit                      | ID 13 (auto-vector IRQ 1-7)

| EraseScrnBuff - fill 512x342 screen with white (-1 longs)
| A2 = screen base, A6 = return addr. Clobbers D2, D3.

| EraseScrnBuff - fill screen buffer with all 1s (white)
| A2 = screen buffer start address (0x3FA700 = ScreenLow)
| A6 = return address (callee-saves pattern, no stack available yet)
| Fills 0x1560 longwords = 21,888 bytes = 512 x 342 / 8 = exactly one screen.
| Called during boot.
EraseScrnBuff:
        MOVEQ.L #-0x1,D3                        | D3 = 0xFFFFFFFF (white pixels)
        MOVE    #0x157F,D2                      | D2 = 5503 (loop count: 5504 longwords = 22016 bytes)
| Screen erase loop body
ERASE_SCRN_LOOP:
        MOVE.L  D3,(A2)+                        | write 4 white bytes (32 pixels); advance
        DBF     D2,ERASE_SCRN_LOOP              | loop until entire buffer cleared
        JMP     (A6)                            | return via A6

| ToDeepShit - unhandled-exception panic handler ($01D2)
| Called via BSR.B from GenExcps table. Saves regs to 0x07FC80
| (secondary save area), computes exception ID = (retaddr - GenExcps)/2,
| then jumps to the memtest-failure display at SysErr2.

| ----------------------------------------------------------
| ToDeepShit - fatal exception handler entry point
| Called via BSR from GenExcps entries. The BSR return address on the stack
| encodes which exception occurred (offset from GenExcps base / 2 = error ID).
| Saves registers if not already saved (debugger-active check via MacJmp bit 7),
| then extracts the 68000 exception stack frame and falls through to SysErr2.
| On 68000 (CPUFlag=0), bus/address errors (IDs 0-2) push an extended frame
| with additional access address and instruction register fields.
ToDeepShit:
        MOVEM.L D0-D7/A0-A7,(0x7FC80).l         | save all 16 regs to 2nd save area
        TST.B   (IWM_MTROFF).l                  | IWM mtrOff: disk drive enables off (motor off)
        LEA     GenExcps(PC),A0                 | A0 = table base
        MOVE.L  (SP)+,D0                        | D0 = BSR return addr (within GenExcps)
        SUB.L   A0,D0                           | D0 = byte offset from GenExcps base
        LSR     #0x1,D0                         | D0 = exception ID (each BSR is 2 bytes)
        BRA.W   SysErr2                         | jump to CritErr display w/ D0 = exception ID
| ----------------------------------------------------------
| BootBeep - generate a short square-wave tone through the VIA/DAC
| Fills the 370-word sound buffer at RAM + $7FD00 (the high bytes) with a
| 4-byte square-wave pattern ($FA40C006 LE -> $C0 $06 $FA $40), writing
| 20 samples per pattern byte, repeated 5 times for 400 sample bytes.
| One word is fetched per scan line (22.25 kHz). A6 = return address.

| Startup beep: fills the sound buffer with a square wave.
| The high byte of each word is the sound sample (Inside Macintosh II-233).
| BEEP_POLL_T1_LOOP waits for the vertical blanking flag (VIA IFR bit 1).
| return address in A6
| Called during boot.
| BootBeep generates a square wave tone using the PWM sound buffer.
| The main sound buffer: 370 words at the top of RAM - $300 ($7FD00 here).
| The low byte of each word is the disk-speed (PWM) value of a 400K drive.
| The interrupt flag polled is CA1 (vertical blanking), not timer 1.
| D3 = duration in ticks (60 Hz), A6 = return address.
BootBeep:
        MOVE.L  #VIA_Base,A5                    | A5 = VIA base (sound enable bit)
        BCLR    #0x7,(A5)                       | clear PB7: enable sound output
        LEA.L   (0x7FD00).l,A0                  | A0 = sound-buffer offset within RAM
        ADDA.L  A3,A0                           | A0 += RAM base -> absolute addr
        MOVE.L  A0,A4                           | A4 = saved base (for smoothing pass)
        MOVEQ.L #0x4,D0                         | D0 = 4 = outer loop count (5 iterations)
| Sound fill: repeat pattern 5 times
BEEP_FILL_REPEAT:
        MOVE.L  #0xFA40C006,D1                  | Square wave sample bytes (long-immediate, byte order $FA,$40,$C0,$06)
| Sound fill: cycle 4 pattern bytes
BEEP_FILL_CYCLE:
        MOVEQ.L #0x13,D2                        | Write 20 samples per pattern byte
| Sound fill: write 20 samples per byte
BEEP_WRITE_SAMPLE:
        MOVE.B  D1,(A0)                         | Write sample byte to sound buffer
        ADDQ.W  #0x2,A0                         | Skip the low byte (disk speed)
        SUBQ.W  #0x1,D2                         | Decrement sample counter
        BNE.B   BEEP_WRITE_SAMPLE               | More samples for this byte
        LSR.L   #0x8,D1                         | Shift to next pattern byte
        BNE.B   BEEP_FILL_CYCLE                 | More pattern bytes
        DBF     D0,BEEP_FILL_REPEAT             | Repeat fill pattern

| BEEP_SMOOTH_FILTER - smooth the sound buffer using weighted average filter
| Applies a 1:2:1 FIR filter to the sound samples to reduce aliasing.
| Then extends the smoothed data to fill the entire buffer.
| Called during boot.
BEEP_SMOOTH_FILTER:
        MOVE.L  A4,A0                           | A0 = start of sound buffer
        LEA.L   0x92(A0),A1                     | A1 = offset 0x92 (filter source: +73 samples)
        MOVEQ.L #0x49,D0                        | 74 samples to smooth
| Sound smoothing: 1:2:1 FIR filter
BEEP_FIR_LOOP:
        MOVE.B  (A1),D2                         | D2 = sample[i+2] (far neighbor)
        ADDQ.W  #0x4,A1                         | Skip to sample[i+4]
        MOVE.B  (A1),D1                         | D1 = sample[i+4]
        ADD     D1,D2                           | D2 = sample[i+2] + sample[i+4]
        SUBQ.W  #0x2,A1                         | Back to sample[i+3]
        MOVE.B  (A1),D1                         | D1 = sample[i+3] (center)
        ADD     D1,D2                           | D2 += center (weighted 1x)
        ADD     D1,D2                           | D2 += center again (weighted 2x)
