| === 68000 Reset Vector Table ===
| On power-on, the 68000 loads SSP from offset 0 and PC from offset 4.
| ROM is at 0x400000, but overlay maps it to 0x000000 during reset.
| --- ROM-variant difference @ $0000 ---
| MAC_128K: checksum $28BA61CE (1984-01)
| MAC_512K: checksum $28BA4E50 (1984-10)
| Reason: the initial SSP doubles as the 32-bit sum of all other 16-bit
| words in ROM; any code-byte change shifts this value.
VECTORS_CONT:
.if ROM_TARGET == MAC_128K
  .long 0x28BA61CE                              | +0: initial SSP (= ROM checksum, Mac 128K)
.else
  .long 0x28BA4E50                              | +0: initial SSP (= ROM checksum, Mac 512K)
.endif
  .long 0x0040002A                              | +4: initial PC = MEMTEST_LOOP (ROM + 0x2A)
| The initial SP value (checksum) is an invalid address - real SP is
| set up later after RAM sizing. It doubles as the ROM checksum word.
  .byte 0x00                                    | +8: Machine Type (0 = Macintosh)
  .byte 0x69                                    | +9: ROM version ($69 = Mac 128K/512K, 1984)

| ROM entry points table (addresses relative to ROM base):
        BRA.W   COLD_START                      | +A: cold start (after test-ROM check)
        BRA.W   BOOT_READ_SETUP_RETRY           | +E: warm start / disk-boot retry
        BRA.W   READ_PHASE_LINES                | +12: read phase lines (SCC bus timing)
TEST_MODE_ENTRY:
        MOVE.B  D0,(A0)                         | +16: test entry (store D0 @ (A0))

| MEMTEST_LOOP - repeated memory test loop (not used on Mac Plus)
| Loops SP times: each iteration checksums ROM and tests RAM.
MEMTEST_LOOP:
        LEA.L   MEMTEST_LOOP_RET(PC),A6         | A6 = return address
        BRA.W   ADDRLINE_TEST                   | call address-line + RAM test (classic phase 2)

| ----------------------------------------------------------
|
| MEMTEST_LOOP_RET - return from memory test; loop or continue boot
|
| Z=0 on failure (bad RAM or ROM checksum mismatch). SP doubles as
| an iteration counter: decrement on each successful pass, loop
| back to MEMTEST_LOOP until counter hits zero. When the loop
| completes, check for an external test-ROM wired at $F80000.
MEMTEST_LOOP_RET:
        BNE.W   CritErr                         | failure: sad-Mac handler
        SUBQ.L  #0x1,SP                         | decrement counter (SP is the counter!)
        MOVE.L  SP,D0                           | test if counter reached zero
        BNE.B   MEMTEST_LOOP                    | not zero: run next pass
| --- External test-ROM check ---
| If a test ROM is wired at $F80000, its signature word is $AA55 and
| its entry address is stored in the next long (MOVEM.L reads both
| into D0 and A0 respectively). If the signature matches, JMP (A0).
        MOVEM.L (TestSoftware).l,D0/A0          | D0 = signature word, A0 = entry addr
        CMPI.W  #0xAA55,D0                      | is the test-ROM signature present?
        BNE.B   COLD_START                      | no test ROM: fall through to warm-start
        JMP     (A0)                            | signature found: jump to test-ROM entry

| ----------------------------------------------------------
| READ_PHASE_LINES - read hardware phase lines to sample bus timing signals
| Reads 3 words from the phase-read address (0xF00000) into D0-D2.
| Used by PHASE_TIMING_INIT below to detect SCC-clock phase.
| Called during boot.
READ_PHASE_LINES:
        MOVEM   (Phase_Read).l,D0-D2            | D0=phase[0], D1=phase[1], D2=phase[2]
        JMP     (A5)                            | return via caller-set A5

| ----------------------------------------------------------
| COLD_START - begin cold start: disable interrupts, sample bus timing
| Reached via the entry-table BRA.W at $000A, or after a failed
| test-ROM signature check. Masks all interrupts, samples bus
| timing, adjusts SCC for detected phase, then sets up screen.
| Called during boot.
COLD_START:
        MOVE    #0x2700,SR                      | supervisor mode, IPL=7 (mask all interrupts)
        LEA.L   PHASE_TIMING_INIT(PC),A5        | A5 = return addr = PHASE_TIMING_INIT
        BRA.B   READ_PHASE_LINES                | call READ_PHASE_LINES

| ----------------------------------------------------------
| PHASE_TIMING_INIT - compute SCC timing slot from phase-read bits
| D0-D2 hold the 3 phase-read words. Low bit of each is summed;
| if sum > 1, one extra SCC access shifts its phase by 128ns.
| Called during boot.
PHASE_TIMING_INIT:
        MOVEQ.L #0x1,D7                         | D7 = mask for low bit
        LEA.L   (SCC_RdCtlB).l,A6               | A6 -> SCC read base (SCC_RdCtlB = 0x9FFFF8)
        MOVE.B  D7,(A6)                         | touch SCC: sync bus timing
        AND     D7,D0                           | D0 = phase_read_0 & 1
        AND     D7,D1                           | D1 = phase_read_1 & 1
        AND     D7,D2                           | D2 = phase_read_2 & 1
        ADD     D2,D0                           | accumulate low bits
        ADD     D1,D0                           | D0 = total (0..3)
        SUBQ.W  #0x1,D0                         | D0 = total - 1
        BLE.B   SCREEN_BUF_INIT                 | if total <= 1, skip phase shift
        TST     (A6)                            | word read: shift SCC phase by 128ns

| ----------------------------------------------------------
| SCREEN_BUF_INIT - screen-buffer address setup (after SCC timing complete)
| RAM base is $600000 (bank 0); screen buffer = RAM + $7A700.
| Called during boot.
SCREEN_BUF_INIT:
        MOVE.L  #0x600000,A3                    | A3 = main RAM base (bank 0)
        MOVE.L  #0x67A700,A2                    | A2 = screen buffer = RAM + $7A700
        LEA     VIA_INIT(PC),A6                 | A6 = return addr after screen clear
        BRA.W   EraseScrnBuff                   | call EraseScrnBuff (clear frame buffer)
| ----------------------------------------------------------
| VIA_INIT -- VIA port A/B initialization (after screen cleared)
| A3 and A2 still hold RAM / screen-buffer base addresses. Configure
| VIA port A (sound volume and buffer, overlay, disk SEL, screen buffer)
| + clock + enable lines, and sound enable).
VIA_INIT:                                       | VIA initialization
        MOVE.L  #VIA_Base,A5                    | A5 = VIA base (PortB = VBase = AVBufB)
        MOVE.B  #0x7B,vBufA(A5)                 | PortA = $7B: volume 3, main sound buffer, overlay on, SEL = 1, main screen
        MOVE.B  #0x7F,vDIRA(A5)                 | DDRA = $7F: PA0-6 outputs, PA7 (SCC W/REQ) input
        MOVE.B  #0x7,(A5)                       | PortB ($0000): RTC ena + clk + data all HIGH
        MOVE.B  #0x87,vDIRB(A5)                 | DDRB ($0400): PortB bit-direction = $87
        MOVE.B  #0x82,vIER(A5)                  | IER = $82: enable the CA1 (vertical blanking) interrupt
        CLR.B   vPCR(A5)                        | PCR ($1800): zero CA1/CA2/CB1/CB2 control
        MOVEQ.L #0x28,D3                        | D3 = 40 ticks = beep duration (~0.67s)
        LEA     IWM_INIT(PC),A6                 | A6 = return addr after BootBeep
        BRA.W   BootBeep                        | generate square-wave boot tone

| ----------------------------------------------------------
| IWM_INIT -- floppy controller: motor off, wait until no drive enable is
| active (status bit 5), then write mode $1F until it reads back: latch,
| asynchronous, 1-s timer off, fast (2-us cells), 8 MHz (IWM Design Spec).
IWM_INIT:                                       | IWM init setup
        MOVE.L  #IWM_PH0L,A0                    | A0 = IWM base ($DFE1FF)
        MOVEQ.L #0x1F,D0                        | D0 = mode $1F

| motor off; mode bits 0-4 read back in the status; write only with motor off
IWM_INIT_LOOP:
        TST.B   mtrOff(A0)                      | mtrOff: motor-on = 0 (/ENBL1, /ENBL2 off)
        TST.B   q6H(A0)                         | Q6H: L6 = 1
        MOVE.B  q7L(A0),D2                      | Q7L: L7 = 0: read the status register
        BTST    #0x5,D2                         | status bit 5: an enable still active (1-second timer)?
        BNE.B   IWM_INIT_LOOP                   | yes -> wait
        AND.B   D0,D2                           | status bits 0-4 = mode bits
        CMP.B   D0,D2                           | mode $1F already?
        BEQ.B   IWM_INIT_DONE                   | yes -> done
        MOVE.B  D0,q7H(A0)                      | Q7H: L7 = 1 with L6 = 1, motor off: write the mode register
        TST.B   q7L(A0)                         | Q7L: L7 = 0, status register again
        BRA.B   IWM_INIT_LOOP                   | check it

| ----------------------------------------------------------
| IWM_INIT_DONE - IWM initialized, now checksum ROM and test RAM
| This is the main memory test call. On success (Z flag set), continues.
| On failure, falls through to CritErr (sad Mac icon).
| Called during boot.
IWM_INIT_DONE:
        TST.B   q6L(A0)                         | Q6L: L6 = 0, read data register selected (read mode)
        SUBA.L  A4,A4                           | A4 = 0 (checksum accumulator)
        ADDQ.W  #0x1,A4                         | A4 = 1 (phase 1 = ROM checksum)
        LEA     BOOT_MEMTEST_PHASE1_RET(PC),A6  | A6 = return address after ROM checksum
        BRA.W   ChecksumRomAndTestMemory        | call ChecksumRomAndTestMemory (phase 1 only)
BOOT_MEMTEST_PHASE1_RET:
        BNE.B   CritErr                         | ROM checksum failed: show sad Mac
        LEA     BOOT_MEMTEST_PHASE2_RET(PC),A6  | A6 = return after RAM address-line test
        BRA.W   ADDRLINE_TEST                   | run RAM address-line test (phase 2)
BOOT_MEMTEST_PHASE2_RET:
        BEQ.W   RAM_FILL_INIT                   | address lines OK: continue boot
| === CritErr - System Error: display sad Mac icon ===
| Saves all registers to the system error save area (0x3FFC80 = SERegs)
| then shows the sad Mac icon with the error code.
| === CritErr - System Error: display sad Mac icon ===
| Saves all registers to the system error save area (0x67FC80 = SERegs)
| then shows the sad Mac icon with the error code in D0/D1.
CritErr:
        MOVEM.L D0-D7/A0-A7,(0x67FC80).l        | Save all 16 regs for debugger (SERegs)
        TST.B   (IWM_MTROFF).l                  | IWM mtrOff: disk drive enables off (motor off)
        LEA.L   (0x7A700).l,A2                  | A2 = screen offset within framebuffer
        ADDA.L  A3,A2                           | A2 += RAM base -> absolute screen addr
        LEA     SADMAC_SCRN_READY(PC),A6        | return addr = SADMAC_SCRN_READY
        BRA.W   EraseScrnBuff                   | Erase screen to white before drawing icon

| ----------------------------------------------------------
| SADMAC_SCRN_READY
| SADMAC_SCRN_READY - prepare to display the error code below the sad Mac icon
| A4 = error code from the failed operation.
SADMAC_SCRN_READY:
        MOVE    A4,D0                           | D0 = error code (low word)
        LEA     SADMAC_DRAW_CODE(PC),A5         | return addr = SADMAC_DRAW_CODE
        BRA.W   ShowSadMac                      | Draw sad Mac icon (in debugger.s)

| SADMAC_DRAW_CODE - draw 6-digit hex error code below the sad Mac icon
| D0.W = high part of error code, D1.W = low part.
| Renders each hex digit as a 3x6 pixel glyph from DT_HEX_FONT.
SADMAC_DRAW_CODE:
        SWAP    D0                              | Move error code to high word
        MOVE    D1,D0                           | D0 = error.high:error.low combined
        LSL.L   #0x8,D0                         | Shift left 8 to align first nibble
        MOVE.L  #0x7D3DD,A2                     | A2 = screen position for error number
        ADDA.L  A3,A2                           | A2 += RAM base -> absolute addr
        MOVEQ.L #0x5,D4                         | D4 = 6 digits to display (0..5)

| HEX_DIGIT_LOOP - hex digit rendering loop: draw one digit per iteration
HEX_DIGIT_LOOP:
        ROL.L   #0x4,D0                         | Rotate next nibble into low 4 bits
        MOVE    D0,D5                           | Copy for masking
        ANDI    #0xF,D5                         | D5 = hex digit value (0-15)
        MULU    #0x3,D5                         | Each glyph is 3 bytes in DT_HEX_FONT
        LEA     DT_HEX_FONT(PC,D5.W),A1         | A1 = glyph data for this digit
        MOVEQ.L #-0x3D,D1                       | D1 = 0xC3 = pixel mask for background
        MOVEQ.L #0x2,D3                         | 3 bytes per glyph (6 scanlines, 2 pixels/byte)

| GLYPH_DRAW_LOOP - draw one glyph byte as two scanlines
GLYPH_DRAW_LOOP:
        MOVE.B  (A1),D5                         | Read glyph byte
        LSR     #0x2,D5                         | Shift right: upper 2 pixels
        OR      D1,D5                           | Merge with background mask
        MOVE.B  D5,(A2)                         | Write to screen (odd scanline)
        ADDA    #scrnRowB,A2                    | Advance one scanline (64 bytes)
        MOVE.B  (A1)+,D5                        | Read glyph byte again
        LSL     #0x2,D5                         | Shift left: lower 2 pixels
        OR      D1,D5                           | Merge with background mask
        MOVE.B  D5,(A2)                         | Write to screen (even scanline)
        ADDA    #scrnRowB,A2                    | Advance one scanline
        DBF     D3,GLYPH_DRAW_LOOP              | Loop for 3 byte pairs (6 scanlines)
        SUBA    #0x17F,A2                       | Move back up 6 scanlines, advance 1 pixel right
        DBF     D4,HEX_DIGIT_LOOP               | Loop for all 6 hex digits
        ADDA.W  #0x1FC,A2                       | A2 = screen addr for blink animation
        MOVE    #0x2700,SR                      | Disable all interrupts (halt state)

| Dead Mac blink loop (infinite, IPL=7)
DEAD_MAC_BLINK:
        ADDQ.L  #0x1,D0                         | Increment blink counter
        SWAP    D0                              | Use alternating bytes
        MOVE.B  D0,(A2)                         | Write to screen (creates flash)
        MOVE.B  (A2),0x1(A2)                    | Copy to adjacent byte (widen flash)
        SWAP    D0                              | Restore counter
        BRA.B   DEAD_MAC_BLINK                  | Loop forever (dead Mac)

