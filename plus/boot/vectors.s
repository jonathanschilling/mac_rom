  .byte 0x00,0x00,0x00,0x04,0x00,0x00           | reserved, cMoreMasters=4, reserved
  .byte 0x00,0x00                               | padding (32 bytes total)

| === Initialize QuickDraw and draw the Happy Mac icon ===
| This is where the screen first shows something other than white.
INIT_QUICKDRAW:
        MOVEQ.L #0x20,D0                        | 32 bytes
        _NewPtrSysClear                         | Allocate switcher param block
        MOVE.L  A0,A1                           | A1 = new block
        LEA.L   DT_SWITCHER_PARAMS(PC),A0       | A0 = default values
        MOVEQ.L #0x20,D0                        | 32 bytes
        _BlockMove                              | Copy defaults into new block
        MOVE.L  A1,(SwitcherTPtr).w             | Store switcher parameter pointer
| Initialize QuickDraw graphics system
| A5 = QuickDraw globals pointer (above current SP)
        LEA.L   0x190(SP),A5                    | A5 -> QD globals area on stack
        PEA.L   -0x4(A5)                        | Push globalPtr parameter
        _InitGraf                               | Initialize QuickDraw (sets up thePort, patterns, etc.)
        PEA.L   -0x200(A6)                      | Push port storage address
        _OpenPort                               | Open the system GrafPort (WMgrPort)
| Draw the Happy Mac icon with startup disk icon
        MOVE.L  (A5),A2                         | A2 = thePort (QuickDraw globals ptr)
        PEA.L   -0x6C(A2)                       | Push arrow cursor address
        _SetCursor                              | Set cursor to arrow
        PEA.L   -0x74(A2)                       | Push screenBits.bounds rect
        MOVE.L  (SP),-(SP)                      | Duplicate rect on stack
        _PaintRect                              | Paint entire screen black
        MOVE.L  #0x100010,-(SP)                 | Push oval size (16,16) for rounded corners
        PEA.L   -0x18(A2)                       | Push portRect address
        _FillRoundRect                          | Fill rounded rect with white (inner area)
| Draw question-mark disk icon (waiting for boot disk)
        LEA.L   DT_mQMark(PC),A0                | Question mark icon data
        MOVE.L  A0,D7                           | D7 = icon address (saved across calls)
        MOVEM.L D7/A5-A6,-(SP)                  | Save regs
        BSR     PlotDisk                        | Draw floppy disk icon with question mark
        MOVEM.L (SP)+,D7/A5-A6                  | Restore regs
        MOVEQ.L #0x0,D4                         | D4 = animation counter
        MOVE.L  (DrvQHdr_Head).w,D6             | D6 = first drive queue element
| Wait until DrvQHdr_Head is non-nil
WAIT_DRIVE_READY:
        BEQ.B   WAIT_DRIVE_READY                | Wait until at least one drive exists
        BTST    #0x4,(SPMisc2).w                | PRAM: start from SCSI?
        BNE     TRY_NEXT_DRIVE                  | Yes: skip floppy, try SCSI first

| === WaitForBootDisk: scan all drives for a bootable disk ===
| Uses the stack as an IOParam block (A0 = SP).
| Reads the first 1024 bytes from each drive and checks for the
| boot block signature 0x4C4B ("LK") at offset 0.
| Called during boot.
WaitForBootDisk:
        MOVE.L  A7,A0                           | A0 = IOParam block (on stack)
        MOVE    #0x1,ioPosMode(A0)              | fsFromStart: read from byte 0
        CLR.L   ioPosOffset(A0)                 | Offset = 0 (start of disk)
        MOVE.L  A6,ioBuffer(A0)                 | A6 = read buffer pointer
        MOVE.L  #0x400,ioReqCount(A0)           | Read 1024 bytes (2 boot blocks)

        TST.L   D6                              | Any drive queue elements?
        BEQ     TRY_NEXT_DRIVE                  | No drives: try SCSI
        MOVE.L  D6,A1                           | A1 = current drive queue element
        MOVE    0x8(A1),D3                      | D3 = driver refNum from DrvQEl
        MOVE    D3,ioRefNum(A0)                 | Set driver for read
        MOVE    D3,(BtDskRfn).w                 | Save boot disk driver refNum
        MOVE    0x6(A1),D3                      | D3 = drive number
        MOVE    D3,ioVRefNum(A0)                | Set drive for read
        MOVE    D3,(BootDrive).w                | Save boot drive number
        MOVEQ.L #0x0,D1                         | D1 = 0 (no eject needed)
        TST.B   (MBState).w                     | Is mouse button down?
        BPL.B   EJECT_DISK                      | Yes: eject this disk
        _Read                                   | Read first 1024 bytes from disk
        BNE.B   DISK_READ_ERROR                 | Read error: check error code
        CMPI    #0x4C4B,(A6)                    | Boot block signature "LK"?
        BNE.B   DISK_NOT_BOOTABLE               | Not bootable: eject and try next
| === Boot disk found! Show Happy Mac and begin loading System ===
        _HideCursor                             | Hide cursor for icon drawing
        MOVEM.L A5-A6,-(SP)                     | Save QD globals and buffer ptr
        LEA.L   HAPPYMAC_SHOWN(PC),A5           | Return to HAPPYMAC_SHOWN after Happy Mac
        BRA     ShowHappyMac                    | Draw the Happy Mac icon

| HAPPYMAC_SHOWN - Happy Mac shown, now boot from the disk
| Called during boot.
HAPPYMAC_SHOWN:
        MOVEM.L (SP)+,A5-A6                     | Restore QD globals and buffer ptr
        BRA     BootFromDisk                    | Load and launch the System file

| ----------------------------------------------------------
| DISK_READ_ERROR - disk read error: check if drive is offline or missing
DISK_READ_ERROR:
        CMPI    #-0x41,D0                       | offLinErr (-65): no disk in drive
        BEQ.B   TRY_NEXT_DRIVE                  | Try next drive
        CMPI    #-0x40,D0                       | noDriveErr (-64): drive disconnected
        BEQ.B   DRIVE_FAILED                    | Remove from boot mask
| DISK_NOT_BOOTABLE - disk not bootable or read error: eject and try next
DISK_NOT_BOOTABLE:
        MOVEQ.L #-0x1,D1                        | D1 = -1 (flag: eject was needed)
| EJECT_DISK - eject disk (also used when mouse button held down)
EJECT_DISK:
        MOVE    #0x7,0x1A(A0)                   | csCode = 7 = eject
        _Control                                | Send eject command to disk driver
        TST     D1                              | Was eject requested (D1=-1)?
        BEQ.B   TRY_NEXT_DRIVE                  | No: just move to next drive
        TST     D0                              | Eject succeeded?
        BEQ.B   SHOW_XMARK_ICON                 | Yes: wait for re-insert
| DRIVE_FAILED - drive failed: remove from boot mask and try next
DRIVE_FAILED:
        MOVE    (BootMask).w,D0                 | Current boot drive mask
        BCLR    D3,D0                           | Clear bit for this drive number
        MOVE    D0,(BootMask).w                 | Update boot mask
| TRY_NEXT_DRIVE - advance to next drive in queue; check SCSI if available
TRY_NEXT_DRIVE:
        JSR     CheckSCSI(PC)                   | Check for SCSI boot disk (if SCSI present)
        MOVE.L  D6,A1                           | A1 = current drive queue element
        MOVE.L  (A1),D6                         | D6 = next element (qLink)
        BNE.B   CHECK_BOOT_MASK                 | More drives: check next one
        MOVE.L  (DrvQHdr_Head).w,D6             | Wrap around to head of drive queue
        BRA.B   ANIMATE_DISK_ICON               | Go animate the disk icon

| CHECK_BOOT_MASK - check if this drive is in the boot mask (eligible for boot)
CHECK_BOOT_MASK:
        MOVE.L  D6,A1                           | A1 = drive queue element
        MOVE    0x6(A1),D3                      | D3 = drive number
        MOVE    (BootMask).w,D0                 | D0 = boot drive mask
        BTST    D3,D0                           | Is this drive still eligible?
        BEQ.B   TRY_NEXT_DRIVE                  | No: skip, try next drive
        BRA     WaitForBootDisk                 | Yes: try reading boot blocks

| SHOW_XMARK_ICON - disk was ejected: show X mark icon briefly, then question mark
SHOW_XMARK_ICON:
        LEA.L   DT_mXMark(PC),A0                | X mark icon (bad disk indicator)
        MOVE.L  A0,D7                           | D7 = icon to draw
        MOVEQ.L #0x8,D5                         | D5 = 8 animation frames before reverting to ?
| ANIMATE_DISK_ICON - animate disk icon: alternate between drawing and erasing
| D4 counts frames, D7 = icon address (0 = erase, nonzero = draw icon)
ANIMATE_DISK_ICON:
        MOVEM.L D3-D7/A5-A6,-(SP)               | Save boot loop state
        LSR     #0x1,D4                         | Shift D4 right: carry = draw/erase toggle
        BCC.B   DRAW_OR_ERASE_ICON              | Carry clear: draw the icon
        MOVEQ.L #0x0,D7                         | Carry set: erase (D7=0 = blank)
| Draw or erase icon (toggle on D4 bit)
DRAW_OR_ERASE_ICON:
        BSR.B   PlotDisk                        | Draw or erase the disk icon
        MOVEM.L (SP)+,D3-D7/A5-A6               | Restore boot loop state
        MOVEQ.L #0x4,D0                         | D0 = 0x00040000
        SWAP    D0                              | (delay counter)
| Busy-wait animation delay
ANIM_DELAY_LOOP:
        SUBQ.L  #0x1,D0                         | Busy-wait ~262,144 iterations
        BNE.B   ANIM_DELAY_LOOP                 | (~0.3 sec at 8 MHz)
        ADDQ.W  #0x1,D4                         | Advance animation frame counter
        SUBQ.W  #0x1,D5                         | Decrement X-mark display counter
        BNE.B   NEXT_BOOT_ATTEMPT               | Still showing X: keep it
        LEA.L   DT_mQMark(PC),A0                | Switch back to question mark icon
        MOVE.L  A0,D7                           | D7 = question mark icon address
| Return to WaitForBootDisk
NEXT_BOOT_ATTEMPT:
        BRA     WaitForBootDisk                 | Try next drive

