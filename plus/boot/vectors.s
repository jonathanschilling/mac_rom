| === 68000 Reset Vector Table ===
| On power-on, the 68000 loads SSP from offset 0 and PC from offset 4.
| ROM is at 0x400000, but overlay maps it to 0x000000 during reset.
| --- ROM-variant difference @ $0000 ---
| v1: checksum $4D1EEEE1 (1986-01)
| v2: checksum $4D1EEAE1 (1986-03 -- branch-condition fixes)
| v3: checksum $4D1F8172 (1986-03 -- SCSI patch; default build)
| Reason: the initial SSP doubles as the 32-bit sum of all other 16-bit
| words in ROM; any code-byte change shifts this value.
.if ROM_TARGET == MAC_PLUS_V1
  .long 0x4D1EEEE1                              | +0: initial SSP (= ROM checksum, Plus v1)
.elseif ROM_TARGET == MAC_PLUS_V2
  .long 0x4D1EEAE1                              | +0: initial SSP (= ROM checksum, Plus v2)
.else
  .long 0x4D1F8172                              | +0: initial SSP (= ROM checksum, Plus v3)
.endif
  .long 0x0040002A                              | +4: initial PC = EBootStart (ROM + 0x2A)
| The initial SP value (checksum) is an invalid address - real SP is
| set up later after RAM sizing. It doubles as the ROM checksum word.
  .byte 0x00                                    | +8: Machine Type (0 = Macintosh)
  .byte 0x75                                    | +9: ROM version ($75 = Mac Plus v3)
| ROM entry points table (addresses relative to ROM base):
        BRA     COLD_START                      | +A: cold start (after version check)
        BRA     DISK_NOT_BOOTABLE               | +E: warm start / restart
        BRA     READ_PHASE_LINES                | +12: read phase lines (bus timing)
        BRA     TEST_MODE_ENTRY                 | +16: test entry
  .long 0x000176F8                              | +1A: offset of resource fork in ROM
        JMP     vDoEject(PC)                    | +1E: eject entry point
  .long 0x00000000                              | +24: reserved
  .long 0x00000000                              | +28: reserved

| === EBootStart: first instruction after 68000 reset ===
| State: all regs = 0 except SP = 0x4D1F8172 (checksum), SR = 0x2700 (supervisor, IPL=7)
| ROM overlay is active: ROM appears at both 0x000000 and 0x400000.
EBootStart:
        BRA     CHECK_TEST_SW                   | Jump to test software check

| ----------------------------------------------------------
|
| TEST_MODE_ENTRY - test mode entry (stores D0 to memory pointed by A0)
|
TEST_MODE_ENTRY:
        MOVE.B  D0,(A0)                         | Store test result to memory pointed by A0

| MEMTEST_LOOP - repeated memory test loop (not used on Mac Plus)
| Loops SP times: each iteration checksums ROM and tests RAM.
MEMTEST_LOOP:
        LEA.L   MEMTEST_LOOP_RET(PC),A6         | A6 = return address
        BRA.W   ChecksumRomAndTestMemory        | call ChecksumRomAndTestMemory (Plus: single phase)

| ----------------------------------------------------------
|
| MEMTEST_LOOP_RET - return from memory test; loop or continue boot
|
| Z=0 on failure (bad RAM or ROM checksum mismatch). SP doubles as
| an iteration counter: decrement on each successful pass, loop
| back to MEMTEST_LOOP until counter hits zero.
MEMTEST_LOOP_RET:
        BNE.W   CritErr                         | failure: sad-Mac handler
        SUBQ.L  #0x1,SP                         | decrement counter (SP is the counter!)
        MOVE.L  SP,D0                           | test if counter reached zero
        BNE.B   MEMTEST_LOOP                    | not zero: run next pass

| ----------------------------------------------------------
| CHECK_TEST_SW - check for external test software at TestSoftware ($0680)
| Trace: D0=0, A0=0 (no test software installed), falls through to COLD_START.
| Called during boot.
CHECK_TEST_SW:
        MOVEM.L (TestSoftware).l,D0/A0          | Load magic + entry address from $0680

        CMPI.L  #0x55AAAA55,D0                  | Check magic signature
        BNE.B   COLD_START                      | No test software: continue normal boot
        LEA.L   COLD_START(PC),A1               | Set return address = COLD_START
        JMP     (A0)                            | Jump to test software

| ----------------------------------------------------------
| READ_PHASE_LINES - read hardware phase lines to sample bus timing signals
| Reads 3 words from the phase-read address (0xF00000) into D0-D2.
| Used by PHASE_TIMING_INIT below to detect SCC-clock phase.
| Called during boot.
READ_PHASE_LINES:
        MOVEM   (Phase_Read).l,D0-D2            | D0=phase[0], D1=phase[1], D2=phase[2]
        JMP     (A5)                            | return via caller-set A5

| ----------------------------------------------------------
| COLD_START - begin cold start: disable interrupts, sample bus timing
| Reached via the entry-table BRA at $000A, or after a failed
| test-software signature check. Masks all interrupts, samples bus
| timing, adjusts SCC for detected phase, then sets up screen.
| Called during boot.
COLD_START:
        MOVE    #0x2700,SR                      | supervisor mode, IPL=7 (mask all interrupts)
        LEA.L   PHASE_TIMING_INIT(PC),A5        | A5 = return addr = PHASE_TIMING_INIT
        BRA.B   READ_PHASE_LINES                | call READ_PHASE_LINES

| ----------------------------------------------------------
|
| PHASE_TIMING_INIT
|
| Called during boot.
| Trace: D0-D2 = phase read results, D7=1, A6=SCC read base, SR=2700.
| Examines the low bit of each phase read word to determine SCC timing.
| On Mac Plus, all three phase reads typically return the same value.
PHASE_TIMING_INIT:
        MOVEQ.L #0x1,D7                         | D7 = bit mask for low bit
        LEA.L   (SCC_RdCtlB-1).l,A6             | A6 -> SCC read base -1
        TST.B   (A6)+                           | Touch SCC to sync bus timing; A6 -> SCC_RdCtlB
        AND     D7,D0                           | D0 = phase_read_0 & 1
        AND     D7,D1                           | D1 = phase_read_1 & 1
        AND     D7,D2                           | D2 = phase_read_2 & 1
        ADD     D2,D0                           | D0 = sum of low bits
        ADD     D1,D0                           | D0 = total (0-3)
        SUBQ.W  #0x1,D0                         | D0 = total - 1
        BLE.B   SCC_TIMING_DONE                 | If total <= 1, skip SCC phase shift
        TST     (A6)                            | Word access shifts SCC phase by 128ns
| SCC timing complete - init VIA and screen buffer
SCC_TIMING_DONE:
        SUBA.L  A3,A3                           | A3 = 0 (clear for later use)
        MOVE.L  #ScreenLow,A2                   | A2 = screen buffer base (0x3FA700)

| Init VIA port B: set bits 0-2,7 as output (RTC data/clock/enable + sound disable)
| Trace: A5 = VIA_PortB (0xEFE1FE)
        MOVE.L  #VIA_PortB,A5                   | A5 = VIA base for register access
        MOVE.B  #0x87,0x400(A5)                 | DDRB = 0x87: PB0-2,7 output
        MOVE.B  #0x87,(A5)                      | PortB = 0x87: RTC disabled (PB2=1), sound off (PB7=1)
| Read initial RTC state: send command byte 0xC1 (= -0x3F = read seconds byte 0)
        MOVEQ.L #-0x3F,D1                       | D1 = 0xC1 = RTC command: read second counter byte 0
        LEA.L   RTC_READ_RETURN(PC),A5          | Return to RTC_READ_RETURN after RTC read
        BRA     ClkNoMem                        | Send 0xC1 to RTC, receive response in D2

| ----------------------------------------------------------
| RTC_READ_RETURN - return from first RTC read
| Trace: D2 = RTC response byte. Check if RTC is valid.
| If D2 = 0xA8, the RTC contains a valid time; read PRAM settings.
| Otherwise, use default settings (D2 = 7 = max volume).
| Called during boot.
RTC_READ_RETURN:
        CMPI.B  #0xA8,D2                        | Check for RTC validity marker
        BEQ.B   RTC_READ_PRAM_VOL               | Valid: read PRAM for volume setting
        MOVEQ.L #0x7,D2                         | Invalid: use default volume = 7
        BRA.B   INIT_VIA_PORT_A                 | Skip PRAM read, use default volume

| ----------------------------------------------------------
| RTC_READ_PRAM_VOL - RTC is valid: read PRAM byte containing speaker volume
| Sends command 0xA1 (= -0x5F) to read PRAM byte with volume setting.
| Called during boot.
RTC_READ_PRAM_VOL:
        MOVEQ.L #-0x5F,D1                       | D1 = 0xA1 = RTC command: read PRAM volume byte
        LEA.L   INIT_VIA_PORT_A(PC),A5          | Return to INIT_VIA_PORT_A
        BRA     ClkNoMem                        | Send cmd, receive PRAM byte in D2

| ----------------------------------------------------------
| INIT_VIA_PORT_A - configure VIA port A with volume and system flags
| Trace: D2 = speaker volume (bits 0-2) from PRAM or default.
| D4 = volume bits extracted from D2.
| Called during boot.
INIT_VIA_PORT_A:
        MOVEQ.L #0x7,D4                         | D4 = volume mask (bits 0-2)
        AND.B   D2,D4                           | D4 = volume from PRAM (0-7)
        MOVEQ.L #-0x8,D2                        | D2 = 0xF8 (template: all flags set except vol)
        ANDI.B  #0x6B,D2                        | D2 = 0x68: PA3=SndBuf(1), PA5=SEL(1), PA6=Page2(1)
        OR.B    D4,D2                           | D2 = 0x68 | volume: PA bits ready to write
| === CRITICAL: turning off ROM overlay ===
| Writing VIA Port A clears bit 4 (MemOverlay). This remaps address 0x000000
| from ROM back to RAM. From this point, the ROM is only at 0x400000.
        MOVE.L  #VIA_PortB,A5                   | A5 = VIA base (via PortB address)
        MOVE.B  D2,0x1E00(A5)                   | Write PortA: sets volume, clears overlay bit
        MOVE.B  #0x7F,0x600(A5)                 | DDRA = 0x7F: PA0-6 output, PA7(SCCwaitrq) input
        MOVE.B  (A5),D6                         | Read PortB: sample mouse button (PB3) state
        LSL.B   #0x4,D6                         | Shift PB3 into bit 7 (sign bit) for later
        MOVE.B  #0x82,0x1C00(A5)                | IER = 0x82: enable Timer 1 interrupt
        CLR.B   0x1800(A5)                      | PCR = 0: CB2 as input (keyboard data)
| Erase screen buffer to all white (0xFF = white pixels)
| A2 = screen base (0x3FA700), 21,888 bytes = 5,472 longwords
        LEA.L   SCRN_ERASED(PC),A6              | Return to SCRN_ERASED after erase
        BRA     EraseScrnBuff                   | Fill screen with 0xFFFFFFFF (white)

| ----------------------------------------------------------
| SCRN_ERASED - screen erased, now produce the startup beep
| Trace: screen is white, VIA Timer 1 ready for sound generation.
| Called during boot.
SCRN_ERASED:
        MOVEQ.L #0x28,D3                        | D3 = 40 ticks = beep duration (~0.67s)
        LEA.L   BEEP_DONE(PC),A6                | Return to BEEP_DONE after beep
        BRA     BootBeep                        | Generate square wave beep via VIA Timer 1

| ----------------------------------------------------------
| BEEP_DONE - startup beep complete, now initialize disk controller
| Trace: beep has sounded, A5 = VIA base.
| Called during boot.
BEEP_DONE:
        BSET    #0x7,(A5)                       | Set PB7: disable sound output after beep

| Init IWM (Integrated Woz Machine - disk controller)
| The IWM has 16 state registers, accessed by reading/writing odd byte addresses.
| Register selection: Q6 and Q7 lines select between data, status, and mode.
| D0 = 0x1F = desired IWM mode register value (async handshake, 1-sec motor timer).
| Loop: turn motor off, read status, set mode if needed, repeat until stable.
        MOVE.L  #IWM_PH0L,A0                    | A0 = IWM base address
        MOVEQ.L #0x1F,D0                        | D0 = desired mode register value
| IWM init: motor off, read status, set mode
IWM_INIT_LOOP:
        TST.B   0x1000(A0)                      | IWM motor off (read MTROFF register)
        TST.B   0x1A00(A0)                      | Set Q6 high (select status register)
        MOVE.B  0x1C00(A0),D2                   | Q7 low: read IWM status register
        BTST    #0x5,D2                         | Bit 5 = ENABLE: is a drive motor on?
        BNE.B   IWM_INIT_LOOP                   | Yes: wait for motor to spin down
        AND.B   D0,D2                           | Mask status with desired mode bits
        CMP.B   D0,D2                           | Is mode register already correct?
        BEQ.B   IWM_INIT_DONE                   | Yes: skip write, continue
        MOVE.B  D0,0x1E00(A0)                   | Q7 high: write mode register = 0x1F
        TST.B   0x1C00(A0)                      | Q7 low: return to status read mode
        BRA.B   IWM_INIT_LOOP                   | Re-read to verify

| ----------------------------------------------------------
| IWM_INIT_DONE - IWM initialized, now checksum ROM and test RAM
| This is the main memory test call. On success (Z flag set), continues to BootPart2.
| On failure, falls through to CritErr (sad Mac icon).
| Called during boot.
IWM_INIT_DONE:
        TST.B   0x1800(A0)                      | Set Q6 low (deselect IWM registers)
        LEA.L   BOOT_MEMTEST_RET(PC),A6         | Return to BOOT_MEMTEST_RET after memtest
        BRA     ChecksumRomAndTestMemory        | Verify ROM checksum + test all RAM

| ----------------------------------------------------------
| BOOT_MEMTEST_RET - return from ChecksumRomAndTestMemory
| Z flag = 1: all tests passed -> continue boot.
| Z flag = 0: test failed -> show sad Mac (CritErr).
| Called during boot.
BOOT_MEMTEST_RET:
        BEQ     BootPart2                       | Tests passed: continue to disk boot

| === CritErr - System Error: display sad Mac icon ===
| Saves all registers to the system error save area (0x3FFC80 = SERegs)
| then shows the sad Mac icon with the error code.
CritErr:
        MOVEM.L D0-D7/A0-A7,(SERegs).l          | Save all registers for debugger

        TST.B   (IWM_MTROFF).l                  | Turn off disk motor
        LEA.L   (ScreenLow).l,A2                | A2 = screen buffer base
        LEA.L   SADMAC_SCRN_READY(PC),A6        | Return to SADMAC_SCRN_READY after screen erase
        BRA     EraseScrnBuff                   | Erase screen to white before drawing sad Mac

| ----------------------------------------------------------
|
| SADMAC_SCRN_READY
|
| SADMAC_SCRN_READY - prepare to display the error code below the sad Mac icon
| A4 = error code from the failed operation.
SADMAC_SCRN_READY:
        MOVE    A4,D0                           | D0 = error code (low word)
        LEA.L   SADMAC_DRAW_CODE(PC),A5         | Return to SADMAC_DRAW_CODE after ShowHappyMac
        BRA     ShowSadMac                      | Show sad Mac icon (not happy Mac)

| SADMAC_DRAW_CODE - draw 6-digit hex error code below the sad Mac icon
| D0.W = high part of error code, D1.W = low part.
| Renders each hex digit as a 3x6 pixel glyph from the DT_HEX_FONT font table.
| Screen position: SEScrnNum (0x3FD3DD) = centered below sad Mac.
SADMAC_DRAW_CODE:
        SWAP    D0                              | Move error code to high word
        MOVE    D1,D0                           | D0 = error.high:error.low combined
        LSL.L   #0x8,D0                         | Shift left 8 to align first nibble
        MOVE.L  #SEScrnNum,A2                   | A2 = screen position for error number
        MOVEQ.L #0x5,D4                         | D4 = 6 digits to display
| HEX_DIGIT_LOOP - hex digit rendering loop: draw one digit per iteration
HEX_DIGIT_LOOP:
        ROL.L   #0x4,D0                         | Rotate next nibble into low 4 bits
        MOVE    D0,D5                           | Copy for masking
        ANDI    #0xF,D5                         | D5 = hex digit value (0-15)
        MULU    #0x3,D5                         | Each glyph is 3 bytes in DT_HEX_FONT
        LEA.L   DT_HEX_FONT(PC,D5.W),A1         | A1 = glyph data for this digit
        MOVEQ.L #-0x3D,D1                       | D1 = 0xC3 = pixel mask for background
        MOVEQ.L #0x2,D3                         | 3 bytes per glyph (6 scanlines, 2 pixels/byte)
| GLYPH_DRAW_LOOP - draw one glyph byte as two scanlines
GLYPH_DRAW_LOOP:
        MOVE.B  (A1),D5                         | Read glyph byte
        LSR     #0x2,D5                         | Shift right: upper 2 pixels
        OR      D1,D5                           | Merge with background mask
        MOVE.B  D5,(A2)                         | Write to screen (odd scanline)
        ADDA    #scrnRowB,A2                    | Advance one scanline (64 bytes)
        MOVE.B  (A1)+,D5                        | Read glyph byte again
        LSL     #0x2,D5                         | Shift left: lower 2 pixels
        OR      D1,D5                           | Merge with background mask
        MOVE.B  D5,(A2)                         | Write to screen (even scanline)
        ADDA    #scrnRowB,A2                    | Advance one scanline
        DBF     D3,GLYPH_DRAW_LOOP              | Loop for 3 byte pairs (6 scanlines)
        SUBA    #0x17F,A2                       | Move back up 6 scanlines, advance 1 pixel right
        DBF     D4,HEX_DIGIT_LOOP               | Loop for all 6 hex digits
| DEAD_MAC_BLINK - infinite loop: flash the error code on screen
| Writes a counter value to screen memory at SEScrnInc to create a
| blinking effect. The Mac is dead; only power cycle can recover.
        MOVE.L  #SEScrnInc,A2                   | A2 = screen address for blink animation
        MOVE    #0x2700,SR                      | Disable all interrupts (halt state)
| Dead Mac blink loop (infinite, IPL=7)
DEAD_MAC_BLINK:
        ADDQ.L  #0x1,D0                         | Increment blink counter
        SWAP    D0                              | Use alternating bytes
        MOVE.B  D0,(A2)                         | Write to screen (creates flash)
        MOVE.B  (A2),0x1(A2)                    | Copy to adjacent byte (widen flash)
        SWAP    D0                              | Restore counter
        BRA.B   DEAD_MAC_BLINK                  | Loop forever (dead Mac)

