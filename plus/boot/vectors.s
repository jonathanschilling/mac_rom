        ADDQ.W  #0x1,D3                         | Pre-increment duration counter
        BRA.B   BEEP_WAIT_VBL                   | Enter wait-and-smooth loop

| BEEP_SMOOTH_FILTER - smooth the sound buffer using weighted average filter
| Applies a 1:2:1 FIR filter to the sound samples to reduce aliasing.
| Then extends the smoothed data to fill the entire buffer.
| Called during boot.
BEEP_SMOOTH_FILTER:
        MOVE.L  A4,A0                           | A0 = start of sound buffer
        LEA.L   0x92(A0),A1                     | A1 = offset 0x92 (filter source: +73 samples)
        MOVEQ.L #0x49,D0                        | 74 samples to smooth
| Sound smoothing: 1:2:1 FIR filter
BEEP_FIR_LOOP:
        MOVE.B  (A1),D2                         | D2 = sample[i+2] (far neighbor)
        ADDQ.W  #0x4,A1                         | Skip to sample[i+4]
        MOVE.B  (A1),D1                         | D1 = sample[i+4]
        ADD     D1,D2                           | D2 = sample[i+2] + sample[i+4]
        SUBQ.W  #0x2,A1                         | Back to sample[i+3]
        MOVE.B  (A1),D1                         | D1 = sample[i+3] (center)
        ADD     D1,D2                           | D2 += center (weighted 1x)
        ADD     D1,D2                           | D2 += center again (weighted 2x)
        ADDQ.W  #0x3,D2                         | Round up (+3 before /4)
        ASR     #0x2,D2                         | D2 /= 4 (1:2:1 average)
        MOVE.B  D2,(A0)                         | Write smoothed sample
        ADDQ.W  #0x2,A0                         | Next output sample (skip odd byte)
        DBF     D0,BEEP_FIR_LOOP                | Loop for 74 samples
| Extend smoothed data: copy samples to fill remaining buffer
        MOVE    #0x127,D0                       | D0 = 296 more samples to fill
| Sound extend: copy filtered data to fill buffer
BEEP_EXTEND_LOOP:
        MOVE.B  -0x4A(A0),(A0)                  | copy from 37 samples back (creates repeat)
        ADDQ.W  #0x2,A0                         | advance to next output (skip odd byte)
        DBF     D0,BEEP_EXTEND_LOOP             | loop for all 296 samples
| BEEP_WAIT_VBL - wait for one VBL tick, then loop back to smooth and refill
BEEP_WAIT_VBL:
        MOVEQ.L #-0x1,D0                        | D0 = max wait counter
        TST     D5                              | Interrupts available?
        BNE.B   BEEP_VBL_POLL                   | No: use IFR polling
        MOVE.L  (Ticks).w,D0                    | Yes: sync to Ticks global
| BootBeep: wait for next tick
BEEP_TICK_WAIT:
        CMP.L   (Ticks).w,D0                    | Wait for tick change
        BEQ.B   BEEP_TICK_WAIT                  | Same tick: wait
        BRA.B   BEEP_DURATION_CHECK             | Tick changed: continue

| BEEP_VBL_POLL - VBL poll: wait for Timer 1 interrupt flag (early boot path)
| Called during boot (2,388,671 times in 30s trace).
BEEP_VBL_POLL:
        BTST    #0x1,0x1A00(A5)                 | Poll VIA IFR: Timer 1 fired?
        DBNE    D0,BEEP_VBL_POLL                | Wait for VBL
