| BEEP_FILL_BUFFER - fill sound buffer with square wave pattern
| Uses 4-byte pattern 0xC0,0x06,0xFA,0x40 repeated to fill 370 bytes.
| The pattern creates a ~3 kHz square wave through the PWM DAC.
