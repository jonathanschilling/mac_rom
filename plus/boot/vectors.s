| EraseScrnBuff - fill screen buffer with all 1s (white)
| A2 = screen buffer start address (0x3FA700 = ScreenLow)
| A6 = return address (callee-saves pattern, no stack available yet)
| Fills 0x1560 longwords = 21,888 bytes = 512 x 342 / 8 = exactly one screen.
| Called during boot.
EraseScrnBuff:
        MOVEQ.L #-0x1,D3                        | D3 = 0xFFFFFFFF (white pixels)
        MOVE    #0x155F,D2                      | D2 = 5471 (loop count: 5472 longwords = 21,888 bytes)
| Screen erase loop body
ERASE_SCRN_LOOP:
        MOVE.L  D3,(A2)+                        | write 4 white bytes (32 pixels); advance
        DBF     D2,ERASE_SCRN_LOOP              | loop until entire buffer cleared
        JMP     (A6)                            | return via A6

| RTC serial protocol: sends a command byte, receives a response byte.
| Uses VIA PortB bits: PB0=data, PB1=clock, PB2=enable (active low).
| Protocol: enable RTC (PB2=0), clock out 8 command bits on PB0/PB1,
| then clock in 8 response bits, then disable RTC (PB2=1).
| return address in A5
| byte to send in D1
| byte returned in D2
| Called during boot.
ClkNoMem:
        ORI     #0x300,SR                       | Disable interrupts during RTC access
        MOVE.L  #VIA_PortB,A1                   | VIA PortB: PB0=RTCdata, PB1=RTCclock, PB2=RTCenable
        MOVE.B  (A1),D3                         | D3 = saved PortB state
        MOVEQ.L #0x1,D4                         | D4 = PB1 mask (clock bit)
        ANDI.B  #0xF9,D3                        | Clear PB1-2 (clock=0, enable=active)
| Decode the RTC command type from D1:
| Bits 6-3 of D1 determine the command class.
| If bits 6-3 = 0b0111 ($38), this is an extended (2-byte) command.
        MOVE    D1,D6                           | D6 = save command byte
        ANDI    #0x78,D6                        | Mask bits 6-3
        CMPI    #0x38,D6                        | Extended command?
        BNE.B   RTC_SINGLE_CMD                  | No: single-byte command
| Extended command: send first byte, then handle second byte
        MOVE    D1,D6                           | D6 = full command word
        LEA.L   RTC_EXT_CMD_SENT(PC),A6         | Return to RTC_EXT_CMD_SENT after first byte
        BRA     WriteRTCByte                    | Write first command byte to RTC

| RTC_EXT_CMD_SENT - first byte of extended command sent; prepare second byte
| Called during boot.
RTC_EXT_CMD_SENT:
        LSR     #0x8,D1                         | Shift second byte into low position
        TST.B   D6                              | Check command direction (read vs write)
        BRA.B   RTC_READ_OR_WRITE               | Continue to read/write decision

| RTC_SINGLE_CMD - single-byte RTC command: check if read or write
| Called during boot.
RTC_SINGLE_CMD:
        TST.B   D1                              | Bit 7 of D1: 0=write, 1=read
| Check D1 sign: negative = read, positive = write
RTC_READ_OR_WRITE:
        BMI.B   RTC_READ_CMD                    | Negative (bit 7 set): read command
| Write command: send the command byte, then send data byte (D2)
        LEA.L   RTC_WRITE_CMD_SENT(PC),A6       | Return to RTC_WRITE_CMD_SENT after command
        BRA     WriteRTCByte                    | Write command byte to RTC

| RTC_WRITE_CMD_SENT - command byte sent for write; now send the data byte
| Called during boot.
RTC_WRITE_CMD_SENT:
        MOVE    D2,D1                           | D1 = data byte to write (from D2)
        LEA.L   RTC_WRITE_DONE(PC),A6           | Return to RTC_WRITE_DONE after data write
        BRA     WriteRTCByte                    | Write data byte to RTC

| RTC_WRITE_DONE - write complete; disable RTC and return
| Called during boot.
RTC_WRITE_DONE:
        BRA.B   RTC_DISABLE_CHIP                | Go to cleanup (disable RTC chip)

| ----------------------------------------------------------
|
| RTC_READ_CMD
|
| RTC_READ_CMD - read command: send command byte, then read response
| Called during boot.
RTC_READ_CMD:
        LEA.L   RTC_READ_CMD_SENT(PC),A6        | Return to RTC_READ_CMD_SENT after command
        BRA     WriteRTCByte                    | Write read-command byte to RTC

| RTC_READ_CMD_SENT - command sent; now clock in the response byte
| Called during boot.
RTC_READ_CMD_SENT:
        LEA.L   RTC_DISABLE_CHIP(PC),A6         | Return to RTC_DISABLE_CHIP after read
        BRA     ReadRTCByte                     | Read response byte into D2

| RTC_DISABLE_CHIP - RTC transaction complete; disable chip and return
| Called during boot.
RTC_DISABLE_CHIP:
        BSET    #0x2,(A1)                       | Set PB2 high: disable RTC chip
        JMP     (A5)                            | return to RTC caller via A5

| Write 8 bits to RTC via VIA PortB bit-bang serial.
| Shifts D1 MSB-first out through PB0 (data), clocking PB1 (clock) for each bit.
| return address in A6
| Called during boot.
WriteRTCByte:
