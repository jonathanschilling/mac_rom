| BEEP_DURATION_CHECK - decrement duration; if done, fill buffer with silence and return
BEEP_DURATION_CHECK:
        DBF     D3,BEEP_SMOOTH_FILTER           | More ticks: smooth and refill
| Beep duration expired: fill buffer with silence ($80 = zero level)
        MOVE.L  A4,A0                           | A0 = sound buffer start
        MOVEQ.L #-0x80,D0                       | D0 = 0x80 (silence = DAC midpoint)
        MOVE    #0x171,D1                       | 370 samples to clear
| Fill sound buffer with silence (0x80)
BEEP_SILENCE_LOOP:
        MOVE.B  D0,(A0)                         | Write silence sample
        ADDQ.W  #0x2,A0                         | Skip odd byte (IWM speed)
        DBF     D1,BEEP_SILENCE_LOOP            | Fill all 370 samples
        JMP     (A6)                            | Return via A6

