        LEA.L   (ToolDispTable).w,A1            | Start filling Toolbox table
        MOVE.L  (ROMBase).w,A2                  | ROM base (0x400000) for absolute addresses
        MOVE    #0x200,D0                       | 512 Toolbox entries to decode
        MOVEQ.L #0x7F,D2                        | Byte mask for delta decode
| Dispatch table decoding loop.
| Each entry is encoded as either:
| - 2-byte delta (high bit clear): delta = ((byte1 << 8) | byte2) * 2 (signed)
| - 1-byte packed (high bit set): low 7 bits encode skip/delta/special
| - 0x00 in low 7 = skip this entry (Unimplemented)
| - 0x7F in low 7 = read next 2 bytes as absolute ROM offset
| - other = delta value * 2 (signed extension)
DECODE_DISP_LOOP:
        MOVE.B  (A0)+,D1                        | Read encoded byte
        BMI.B   DISP_PACKED_ENTRY               | High bit set: 1-byte packed format
        ASL     #0x8,D1                         | High bit clear: 2-byte format
        MOVE.B  (A0)+,D1                        | D1 = 16-bit delta (word-scaled)
| Dispatch: double delta for byte offset
DISP_DOUBLE_DELTA:
        ADD     D1,D1                           | D1 *= 2 (convert word offset to byte offset)
        EXT.L   D1                              | Sign-extend to 32 bits
        BEQ.B   DETECT_CPU_TYPE                 | Delta = 0: special case (switch tables)
| Dispatch: add delta to ROM ptr, store in table
DISP_ADD_DELTA:
        ADDA.L  D1,A2                           | A2 += delta (advance ROM pointer)
        MOVE.L  A2,(A1)                         | Store handler address in dispatch table
| Dispatch: advance to next table entry
DISP_NEXT_ENTRY:
        ADDQ.W  #0x4,A1                         | Advance to next dispatch table entry
        SUBQ.W  #0x1,D0                         | Decrement entry counter
        BNE.B   DECODE_DISP_LOOP                | More entries: decode next
| Toolbox table done (D0 reaches 0). Switch to OS table:
        MOVEQ.L #-0x1,D0                        | D0 = -1 (wraps to 0xFFFF = 65535 max)
        LEA.L   (DispatchTab).w,A1              | A1 = OS trap table at $400
        BRA.B   DECODE_DISP_LOOP                | Continue decoding for OS traps

| ----------------------------------------------------------
| DISP_PACKED_ENTRY - 1-byte packed dispatch entry (high bit was set)
| Low 7 bits: 0 = skip, 0x7F = absolute, other = short delta.
| Called during boot.
DISP_PACKED_ENTRY:
        AND     D2,D1                           | Mask to low 7 bits
        BEQ.B   DISP_NEXT_ENTRY                 | 0 = skip (leave as Unimplemented)
        CMP     D2,D1                           | Is it 0x7F (absolute offset)?
        BNE.B   DISP_DOUBLE_DELTA               | No: treat as short delta, go to DISP_DOUBLE_DELTA
| 0x7F = absolute 4-byte ROM offset follows
        MOVEQ.L #0x3,D3                         | Read 4 bytes
| Dispatch: read 4-byte absolute offset
DISP_READ_ABSOLUTE:
        ASL.L   #0x8,D1                         | Shift accumulator left 8 bits
        MOVE.B  (A0)+,D1                        | Read next byte into low position
        DBF     D3,DISP_READ_ABSOLUTE           | Loop 4 times: build 32-bit offset
        MOVE.L  (ROMBase).w,A2                  | Reset A2 to ROM base
        BRA.B   DISP_ADD_DELTA                  | Add offset and store address

| === Dispatch table decode complete ===
| All trap handler addresses are now installed in the OS and Toolbox
| dispatch tables. Next: detect CPU type (68000 vs 68020).
| Called during boot.
| === Detect CPU type (68000 vs 68010 vs 68020) ===
| Tries executing a 68020-only MOVEC instruction. If it causes an
| illegal instruction exception, we're on a 68000 or 68010.
| Result stored in CPUFlag: 0=68000, 1=68010, 2=68020.
DETECT_CPU_TYPE:
        LEA.L   (IllegalInstructionVector).w,A1 | Save old illegal instruction vector
        MOVE.L  (A1),D2                         | D2 = save old illegal insn vector
        LEA.L   ILLEGAL_INSN_TRAP(PC),A0        | Install our test handler
        MOVE.L  A0,(A1)                         | Vector $10 -> ILLEGAL_INSN_TRAP
        MOVE.L  A7,A0                           | Save SP for restore after exception
        CLR     -(SP)                           | Push dummy frame
        MOVEQ.L #0x2,D1                         | Assume 68020 (CPUFlag=2)
        MOVEQ.L #0x1,D0                         | Value to write via MOVEC
  .short 0x4E7B,0x0002                          | MOVEC D0,CACR (68020 only)
        BRA.B   CPU_DETECTED                    | If we get here, it's a 68020

| ILLEGAL_INSN_TRAP - illegal instruction handler (MOVEC failed = not 68020)
| Check exception frame format to distinguish 68000 from 68010.
| Called during boot.
ILLEGAL_INSN_TRAP:
        MOVEQ.L #0x1,D1                         | Assume 68010 (CPUFlag=1)
        CMPI    #0x10,0x6(SP)                   | Check frame format word
        BEQ.B   CPU_DETECTED                    | $10 = 68010 format
        MOVEQ.L #0x0,D1                         | Otherwise 68000 (CPUFlag=0)
| CPU detected - restore SP, set CPUFlag
CPU_DETECTED:
        MOVE.L  A0,SP                           | Restore SP (discard exception frame)
        MOVE.L  D2,(A1)                         | Restore original illegal insn vector
        MOVE.B  D1,(CPUFlag).w                  | Store CPU type: 0/1/2

| Install A-line trap dispatcher based on CPU type.
| 68020 uses a faster dispatch path with cache instructions.
        LEA.L   EMT1010_TrapDispatch(PC),A0     | Default: 68000 dispatcher
        BEQ.B   INSTALL_ATRAP                   | CPUFlag=0: use 68000 dispatcher
        LEA.L   ATrap68020(PC),A0               | CPUFlag>0: use 68020 dispatcher
| Install A-line handler, begin manager init
INSTALL_ATRAP:
        MOVE.L  A0,(ATrapVector).w              | Install A-line exception handler

| === Initialize system utilities and read PRAM settings ===
        _InitUtil                               | Init system utilities (parameter RAM)
| Read PRAM settings: cursor scaling, keyboard repeat, caret blink, double-click
        BTST    #0x6,(SPMisc2).w                | PRAM misc: cursor scaling enabled?
        SNE.B   (CrsrScale).w                   | Set CrsrScale from PRAM
| Decode keyboard auto-repeat threshold and rate from SPKbd PRAM byte
        MOVEQ.L #-0x4,D1                        | D1 = 0xFFFFFFFC (mask for 4-byte align)
        MOVEQ.L #0xF,D0                         | D0 = low nibble mask
        MOVE.B  (SPKbd).w,D2                    | D2 = keyboard PRAM byte
        AND.B   D2,D0                           | D0 = low nibble: auto-repeat rate
        ADD     D0,D0                           | D0 *= 2 (scale to ticks)
        SWAP    D0                              | Move to high word (KeyThresh format)
        MOVE.B  D2,D0                           | D0 low = PRAM byte again
        LSR     #0x2,D0                         | Shift high nibble: repeat threshold
        AND     D1,D0                           | Align to 4-tick boundary
        SWAP    D0                              | Combine: high=rate, low=threshold
        MOVE.L  D0,(KeyThresh).w                | Store auto-key threshold + rate
| Decode caret blink time and double-click time from SPClikCaret PRAM byte
        MOVEQ.L #0xF,D0                         | D0 = 15 (16 VIA dispatch entries)
        MOVE.B  (SPClikCaret).w,D2              | D2 = click/caret PRAM byte
        AND.B   D2,D0                           | D0 = low nibble: caret blink rate
        LSL     #0x2,D0                         | Scale to ticks (* 4)
        MOVE.L  D0,(CaretTime).w                | Store caret blink interval
        MOVE.B  D2,D0                           | D0 = PRAM byte again
        LSR     #0x2,D0                         | Shift high nibble: double-click time
        AND     D1,D0                           | Align to 4-tick boundary
        MOVE.L  D0,(DoubleTime).w               | Store double-click interval

| === Initialize the major system managers ===
        BSR     INIT_SYS_ZONE                   | Additional init (set up _SwapFont vector)
        CLR     -(SP)                           | Push refNum result space
        _InitResources                          | Open System resource file (System/Finder)
        ADDQ.W  #0x2,SP                         | Discard result (refNum)
| Initialize Time Manager
        MOVEQ.L #0x12,D0                        | 18 bytes for TimeMgr vars
        _NewPtrSysClear                         | Allocate in system heap
        MOVE.L  A0,(TimeVars).w                 | Store TimeMgr vars pointer
        LEA.L   0x8(A0),A1                      | Point to timer queue header
        JSR     InitQueue(PC)                   | Init timer queue: flags=0, head=nil
| Initialize SCC (serial ports) and keyboard
        BSR     InitSCC                         | Reset SCC, set up serial port registers
        JSR     InitKeyboard(PC)                | Detect keyboard model, set up VIA SR
| Initialize Drive Queue and I/O Manager
        LEA.L   (DrvQHdr_Flags).w,A1            | Drive queue header
        JSR     InitQueue(PC)                   | Init drive queue: flags=0, head=nil
        BSR     InitIOMgr                       | Build Unit Table, install ROM drivers

| Third diagnostic ROM checkpoint at 0xF80088
        MOVEM.L (0xF80088).l,D0/A0              | Check for I/O diagnostic ROM

        CMPI.L  #0x55AAAA55,D0                  | Diagnostic ROM signature?
        BNE.B   ENABLE_INTERRUPTS               | Not present: continue boot
        LEA.L   INSTALL_ATRAP(PC),A1            | Return to INSTALL_ATRAP after diagnostic
        JMP     (A0)                            | Jump to diagnostic code

