| === ENABLE_INTERRUPTS: Enable interrupts and prepare for Finder launch ===
| All hardware is initialized, drivers installed, Resource Manager open.
| Now enable interrupts, init QuickDraw, and show the Happy Mac / disk icon.
| Called during boot.
ENABLE_INTERRUPTS:
        MOVE    #0x2000,SR                      | Drop IPL to 0: ALL interrupts enabled
        CLR     (SysVersion).w                  | System version = 0 (not yet known)
        MOVE.L  (SysZone).w,(RAMBase).w         | RAMBase = start of system heap
        MOVE.B  #0xFE,(AlarmState).w            | Alarm: enabled, not yet triggered
        LEA.L   P_mGNEFilter(PC),A0             | Install default GetNextEvent filter
        MOVE.L  A0,(GNEFilter).w                | Install GetNextEvent filter (ROM default)
        CLR.L   (IAZNotify).w                   | No init-app-zone notification
        MOVE    #-0x81,(DiskVars_FlEvtMask).w   | Floppy event mask: all except eject
| Clear all 8 package handle slots (PACK 0-7)
        MOVEQ.L #0x7,D0                         | D0 = 7 (8 package handles)
        LEA.L   (AppPacks).w,A0                 | AppPacks[0..7]
| Clear AppPacks[0..7]
CLEAR_APPACKS_LOOP:
        CLR.L   (A0)+                           | Each PACK handle = nil
        DBF     D0,CLEAR_APPACKS_LOOP           | Clear next PACK handle
        BRA.B   INIT_QUICKDRAW                  | Jump past DT_SWITCHER_PARAMS data

| ----------------------------------------------------------
| DT_SWITCHER_PARAMS - default Switcher parameter table (32 bytes)
| Copied to SwitcherTPtr at boot. Controls task switching behavior.
DT_SWITCHER_PARAMS:
  .byte 0x04,0x00,0x04,0x00,0x0C,0x00           | stackSize=0x0400, heapSize=0x0400, misc=0x0C00
  .byte 0x08,0x00,0x0B,0x80,0x00,0x80           | reserved, screen bounds (0x0B80, 0x0080)
  .byte 0x03,0x76,0x00,0x02,0x03,0x84           | bounds cont (0x0376, 0x0002, 0x0384)
