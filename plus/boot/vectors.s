| === Build A-line trap dispatch tables ===
| Two tables: OS traps (256 entries at $400) and Toolbox traps (512 entries at $800).
| First fill both with Unimplemented trap handler, then decode the compressed
| ROM dispatch table (TrapDispatchTbl) to install actual handler addresses.
