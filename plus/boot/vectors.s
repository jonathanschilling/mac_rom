| return address in A6
| Called during boot.
| BootBeep generates a square wave tone using the PWM sound buffer.
| The Mac sound system uses a 370-byte buffer at SoundLow (0x3FFD00).
| Even bytes are sound samples, odd bytes are IWM motor speed data.
| VIA Timer 1 clocks the DAC at 22,255 Hz, producing the sample rate.
| D3 = duration in ticks (60 Hz), A6 = return address.
