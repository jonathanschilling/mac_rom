        MOVE    #0xD00,D0                       | Delay counter (~3300 iterations)
| Sound DMA settling delay
BEEP_DMA_DELAY:
        DBF     D0,BEEP_DMA_DELAY               | Busy wait for sound buffer DMA sync
        MOVEQ.L #0x4,D0                         | Repeat fill 5 times (5 * 4 * 20 = 400 bytes)
| Sound fill: repeat pattern 5 times
