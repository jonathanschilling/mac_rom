| Compressed trap dispatch table
|
| Apple source: DispTable.a. Read once at startup by the decoder in
| vectors.s (DECODE_DISP_LOOP), which fills the Toolbox dispatch table
| (512 entries at ToolDispTable) and the OS dispatch table (256 entries at
| DispatchTab) with the ROM addresses of the trap handlers; slots it skips
| keep the Unimplemented handler. Encoding: see the comment at
| TrapDispatchTbl.
|
| References: Inside Macintosh Vol II, Ch 13: The Trap Dispatcher

